ROYAL_NOTE = ("**وهذا من النجوم الملكية الأربعة** التي عدّها الفرس "
              "حرّاسًا للجهات الأربع، وأعظمها أثرًا في التراث كلّه.")


def read(star: dict) -> str:
    """
    نصّ يخصّ نزول هذا النجم على هذا الجِرم بعينه.
    ويرجع فارغًا إن جُهل الجِرم، فلا يُخترَع كلام.
    """
    body = (star or {}).get("body", "")
    on = ON.get(body)
    if not on:
        return ""
    what, how = on
    nature = (star.get("meaning") or "").strip().rstrip("،.")
    orb = star.get("orb")

    parts = [
        f"نزل **{star.get('star', '')}** على {body} — أي على {what}.",
        f"وطبع هذا النجم: {nature}.",
        how + ".",
    ]
    if isinstance(orb, (int, float)):
        for limit, note in TIGHT:
            if orb < limit:
                parts.append(note)
                break
    if star.get("royal"):
        parts.append(ROYAL_NOTE)
    return " ".join(p for p in parts if p).strip()


