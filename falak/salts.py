def for_sign(sign: str) -> dict | None:
    d = SALTS.get(sign)
    return dict(d, sign=sign) if d else None


def read(chart: dict) -> dict:
    """
    ملحُ المولد عند كيري يُؤخذ من **برج الشمس**. ونذكر معه برج
    الطالع والقمر، فبعض من كتب بعده يعتدّ بهما — ونقول إن ذلك
    خلافٌ بينهم لا اتّفاق.
    """
    def sign_of(name):
        for b in chart.get("bodies", []):
            if b["name"] == name:
                return b.get("sign")
        return None

    sun = sign_of("الشمس")
    moon = sign_of("القمر")
    asc = (chart.get("angles", {}).get("الطالع") or {}).get("sign")

    out = {"caveat": CAVEAT, "history": HISTORY, "all": SALTS}
    if sun:
        out["birth"] = for_sign(sun)
        out["birth_note"] = (
            f"**ملح مولدك عند كيري: {SALTS[sun]['salt']}** — لأنّ شمسك "
            f"في {sun}. وهو الذي عناه بـ«ملح المولد».")
    extra = []
    for label, s in (("الطالع", asc), ("القمر", moon)):
        if s and s != sun:
            extra.append({"role": label, **for_sign(s)})
    if extra:
        out["also"] = extra
        out["also_note"] = (
            "وبعض من كتب بعد كيري يعتدّ ببرج الطالع أو القمر كذلك — "
            "**وهذا خلافٌ بينهم لا اتّفاق**، فنعرضه ولا نُرجّح.")
    return out


