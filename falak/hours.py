_SUN_CACHE: dict = {}
_TBL_CACHE: dict = {}


def clear_cache():
    _SUN_CACHE.clear()
    _TBL_CACHE.clear()


def _sun_times(day: datetime, lat: float, lon: float, tz):
    """
    (شروق، غروب) ليوم بعينه.
    مخزَّن مؤقّتًا: حسابه يمرّ على ٢٨٨ خطوة، ويُطلب مرارًا لليوم نفسه
    عند تقييم أغراض الاختيارات الثلاثين.
    """
    key = (day.date().isoformat(), round(lat, 4), round(lon, 4), str(tz))
    hit = _SUN_CACHE.get(key)
    if hit is None:
        ev = ephem.sun_events(day, lat, lon, tz)
        hit = (ev.get("الشروق"), ev.get("الغروب"))
        if len(_SUN_CACHE) > 4000:
            _SUN_CACHE.clear()
        _SUN_CACHE[key] = hit
    return hit


def day_of_hours(when: datetime, lat: float, lon: float) -> datetime:
    """
    اليوم الفلكي يبدأ بالشروق لا بمنتصف الليل.
    فمن كان قبل شروق يومه فهو في ليل اليوم السابق.
    """
    tz = when.tzinfo
    d0 = when.replace(hour=0, minute=0, second=0, microsecond=0)
    rise, _ = _sun_times(d0, lat, lon, tz)
    if rise and when < rise:
        return d0 - timedelta(days=1)
    return d0


def hours_for(date_local: datetime, lat: float, lon: float, tzname: str) -> dict:
    """
    جدول الساعات الأربع والعشرين ليوم فلكي كامل: من شروقه إلى شروق الذي يليه.
    """
    tz = ZoneInfo(tzname)
    d0 = date_local.replace(hour=0, minute=0, second=0, microsecond=0)
    if d0.tzinfo is None:
        d0 = d0.replace(tzinfo=tz)

    ckey = (d0.date().isoformat(), round(lat, 4), round(lon, 4), tzname)
    cached = _TBL_CACHE.get(ckey)
    if cached is not None:
        return cached

    rise, set_ = _sun_times(d0, lat, lon, tz)
    rise2, _ = _sun_times(d0 + timedelta(days=1), lat, lon, tz)
    if not (rise and set_ and rise2):
        return {"error": "تعذّر حساب الشروق والغروب في هذا الموضع "
                         "(قد يكون قرب القطب حيث لا تشرق الشمس أو لا تغرب)."}

    day_len = (set_ - rise) / 12
    night_len = (rise2 - set_) / 12

    ruler = DAY_RULER[d0.weekday()]
    start_idx = CHALDEAN.index(ruler)

    rows = []
    for i in range(24):
        planet = CHALDEAN[(start_idx + i) % 7]
        if i < 12:
            a = rise + day_len * i
            b = rise + day_len * (i + 1)
            part, num = "نهارية", i + 1
        else:
            a = set_ + night_len * (i - 12)
            b = set_ + night_len * (i - 11)
            part, num = "ليلية", i - 11
        use = HOUR_USE[planet]
        rows.append({
            "index": i + 1, "part": part, "number": num,
            "planet": planet, "symbol": PLANET_SYMBOL[planet],
            "nature": NATURE[planet],
            "start": a, "end": b,
            "start_text": a.strftime("%H:%M"), "end_text": b.strftime("%H:%M"),
            "minutes": round((b - a).total_seconds() / 60, 1),
            **use,
        })

    out = {
        "date": d0.date().isoformat(),
        "weekday": WEEKDAY_AR[d0.weekday()],
        "tz": tzname, "lat": lat, "lon": lon,
        "day_ruler": ruler, "day_ruler_symbol": PLANET_SYMBOL[ruler],
        "day_ruler_note": (f"حاكم {WEEKDAY_AR[d0.weekday()]} هو {ruler}، "
                           f"وهو الذي يحكم أوّل ساعة من نهاره، ويصبغ اليوم كلّه بطبعه."),
        "sunrise": rise, "sunset": set_, "next_sunrise": rise2,
        "sunrise_text": rise.strftime("%H:%M"), "sunset_text": set_.strftime("%H:%M"),
        "day_hour_minutes": round(day_len.total_seconds() / 60, 1),
        "night_hour_minutes": round(night_len.total_seconds() / 60, 1),
        "hours": rows,
    }
    if len(_TBL_CACHE) > 2000:
        _TBL_CACHE.clear()
    _TBL_CACHE[ckey] = out
    return out


def hour_at(when: datetime, lat: float, lon: float, tzname: str) -> dict | None:
    """أيّ ساعة كوكبية نحن فيها الآن."""
    tz = ZoneInfo(tzname)
    if when.tzinfo is None:
        when = when.replace(tzinfo=tz)
    base = day_of_hours(when, lat, lon)
    tbl = hours_for(base, lat, lon, tzname)
    if "error" in tbl:
        return None
    for h in tbl["hours"]:
        if h["start"] <= when < h["end"]:
            return {**h, "day_ruler": tbl["day_ruler"], "weekday": tbl["weekday"]}
    return None


def best_hours(date_local: datetime, lat: float, lon: float, tzname: str,
               wanted: list[str], day_only: bool = True) -> list[dict]:
    """ساعات اليوم التي يحكمها كوكب من الكواكب المطلوبة."""
    tbl = hours_for(date_local, lat, lon, tzname)
    if "error" in tbl:
        return []
    return [h for h in tbl["hours"]
            if h["planet"] in wanted and (not day_only or h["part"] == "نهارية")]


def for_purpose(date_local: datetime, lat: float, lon: float, tzname: str,
                purpose: str, day_only: bool = True) -> dict:
    """أفضل ساعات اليوم لغرض بعينه."""
    wanted = PURPOSE_HOURS.get(purpose)
    if not wanted:
        return {"error": f"غرض غير معروف: {purpose}. المتاح: "
                         + "، ".join(PURPOSE_HOURS)}
    hits = best_hours(date_local, lat, lon, tzname, wanted, day_only)
    return {"purpose": purpose, "planets": wanted,
            "hours": [{k: v for k, v in h.items() if k not in ("start", "end")}
                      for h in hits]}


def day_summary(date_local: datetime, lat: float, lon: float, tzname: str) -> dict:
    """
    خلاصة الساعات لسطرين في النشرة اليومية:
    حاكم اليوم، وأحمد ساعات النهار، وأثقلها.
    """
    tbl = hours_for(date_local, lat, lon, tzname)
    if "error" in tbl:
        return {"error": tbl["error"]}
    day = [h for h in tbl["hours"] if h["part"] == "نهارية"]
    good = [h for h in day if h["planet"] in ("المشتري", "الزهرة")]
    hard = [h for h in day if h["planet"] in ("زحل", "المريخ")]
    fmt = lambda hs: "، ".join(f"{h['start_text']}–{h['end_text']} ({h['planet']})"
                               for h in hs)
    return {
        "day_ruler": tbl["day_ruler"],
        "sunrise": tbl["sunrise_text"], "sunset": tbl["sunset_text"],
        "hour_minutes": tbl["day_hour_minutes"],
        "good": [{k: v for k, v in h.items() if k not in ("start", "end")} for h in good],
        "hard": [{k: v for k, v in h.items() if k not in ("start", "end")} for h in hard],
        "line_good": fmt(good), "line_hard": fmt(hard),
    }


def render_text(tbl: dict, only: str = "") -> str:
    """جدول الساعات نصًّا جاهزًا للنسخ."""
    if "error" in tbl:
        return tbl["error"]
    lines = [f"#ساعات_الكواكب {tbl['weekday']} {tbl['date']}",
             f"حاكم اليوم {tbl['day_ruler']} {tbl['day_ruler_symbol']} — "
             f"الشروق {tbl['sunrise_text']} والغروب {tbl['sunset_text']}",
             f"طول الساعة النهارية {tbl['day_hour_minutes']:.0f} دقيقة، "
             f"والليلية {tbl['night_hour_minutes']:.0f} دقيقة.", ""]
    part = None
    for h in tbl["hours"]:
        if only and h["part"] != only:
            continue
        if h["part"] != part:
            part = h["part"]
            lines.append(f"— الساعات ال{part} —")
        lines.append(f"{h['start_text']} إلى {h['end_text']}  "
                     f"ساعة {h['planet']} {h['symbol']} ({h['nature']}) — {h['طبعها']}")
    return "\n".join(lines)
