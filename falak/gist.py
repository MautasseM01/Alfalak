# ١ — النشرة اليومية
# ══════════════════════════════════════════════════════════════
def bulletin(data: dict) -> dict:
    s = data.get("summary") or {}
    voc = s.get("voc") or []
    mansions = s.get("mansions") or []
    mood = (mansions[0].get("mood") if mansions else "") or ""

    tone = {
        "سعيدة جدًا": "يوم مفتوح: ما تبدأه اليوم يمضي.",
        "سعيدة": "يوم طيّب لِما تريد أن تبدأه.",
        "ممتزجة": "يوم متوسّط: فيه ما يُعين وفيه ما يُعطّل.",
        "نحسة": "يوم ثقيل. أجّل ما يحتمل التأجيل.",
    }.get(mood, "يوم عاديّ.")

    lines = [tone]

    if voc:
        v = voc[0]
        hrs = v.get("hours", 0)
        lines.append(
            f"وفيه فترة من {v['start']} تمتدّ نحو {hrs:.0f} ساعات، "
            "يُنصح فيها بألّا تُوقّع عقدًا ولا تبدأ مشروعًا. "
            "وهي ممتازة للترتيب وإنهاء ما بدأته سابقًا."
            if hrs >= 1 else
            f"وفيه فترة قصيرة من {v['start']} يُفضَّل ألّا تبدأ فيها أمرًا جديدًا."
        )
    else:
        lines.append("ولا فترة تُجتنَب فيه: الوقت كلّه صالح للعمل.")

    retro = s.get("retrogrades") or []
    if retro:
        names = "، ".join(retro[:3])
        lines.append(
            f"و{names} تسير الآن في الاتجاه المعاكس ظاهريًّا — "
            "وهذا وقت مراجعة ما مضى أكثر منه وقت ابتداء جديد."
        )

    times = s.get("sun_times") or {}
    then = ""
    if times.get("الشروق") and times.get("الغروب"):
        then = (f"شروق الشمس {times['الشروق']} وغروبها {times['الغروب']}، "
                "وعليهما تُقسَّم ساعات اليوم.")
    return _wrap("خلاصة يومك", lines, then)


# ══════════════════════════════════════════════════════════════
# ٢ — خريطة الميلاد
# ══════════════════════════════════════════════════════════════
def chart(data: dict) -> dict:
    by = {b["name"]: b for b in data.get("bodies", [])}
    sun = by.get("الشمس", {})
    moon = by.get("القمر", {})
    asc = (data.get("angles") or {}).get("الطالع", {})
    dom = data.get("dominants") or {}
    el = dom.get("elements") or {}
    top_el = next(iter(el), "")

    ELEM = {
        "ناري": "متحمّس، تبدأ بسرعة وتملّ الانتظار",
        "ترابي": "عمليّ، تُصدّق ما يُلمَس وتبني على مهل",
        "هوائي": "ذهنيّ، تعيش في الأفكار والكلام والناس",
        "مائي": "شعوريّ، تقرأ ما لا يُقال وتتأثّر بما حولك",
    }

    lines = []
    if sun and moon and asc:
        lines.append(
            f"ثلاثة تكفي للبداية: وُلدت والشمس في {sun.get('sign')}، "
            f"والقمر في {moon.get('sign')}، وكان {asc.get('sign')} صاعدًا "
            "في الأفق شرقًا."
        )
        lines.append(
            f"الأولى تصف ما تريده من حياتك، والثاني ما يُريح قلبك، "
            f"والثالث الصورة التي يراك بها الناس أوّل مرّة — "
            f"وقد تكون مختلفة عمّا أنت عليه في البيت."
        )
    if top_el in ELEM:
        lines.append(f"والغالب على طبعك أنك {ELEM[top_el]}.")

    then = ("وتحت هذا تفصيل كل كوكب: أين وقع، وماذا يعني ذلك عندك. "
            "اقرأ ما يعنيك ودع ما لا يعنيك — لا أحد يقرأ خريطته كلّها "
            "في جلسة.")
    return _wrap("خلاصة خريطتك", lines, then)


