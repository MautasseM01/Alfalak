# ٤ — البحث عن أفضل وقت
# ══════════════════════════════════════════════════════════════
def search(data: dict) -> dict:
    best = data.get("best") or []
    if not best:
        return _wrap("خلاصة", ["لم أجد يومًا في هذا المدى."])
    top = best[0]
    day = _ar_day(top["date"])
    h = (top.get("best_hours") or [None])[0]

    lines = [
        f"أفضل يوم وجدته لـ«{data.get('purpose')}» هو "
        f"{day} {top['date']}."
    ]
    if h:
        lines.append(
            f"وأفضل ساعة فيه بين {h['start_text']} و{h['end_text']}."
        )
    good = [x for x in best if x["score"] >= 70]
    if len(good) > 1:
        lines.append(
            f"ومعه {len(good) - 1} يومًا آخر يصلح، فإن لم يناسبك "
            "الأوّل فانظر ما بعده."
        )
    elif len(good) <= 1:
        lines.append(
            "ولم أجد في هذا المدى أيامًا كثيرة جيّدة. "
            "وسّع المدى أو اقبل بيوم متوسّط — فالانتظار له ثمن أيضًا."
        )
    then = ("اضغط أيّ يوم لترى لماذا نال درجته. والدرجة تصف حال "
            "السماء العامّ، ولا تعرف ظروفك أنت.")
    return _wrap("خلاصة البحث", lines, then)


