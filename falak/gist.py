# ٦ — ساعات الكواكب
# ══════════════════════════════════════════════════════════════
def hours(data: dict) -> dict:
    cur = data.get("current")
    lines = [
        "قسّم القدماء ما بين شروق الشمس وغروبها اثنتي عشرة ساعة، "
        "وما بين الغروب والشروق اثنتي عشرة أخرى. فساعات النهار "
        "تطول صيفًا وتقصر شتاءً، وليست ستّين دقيقة."
    ]
    if cur:
        lines.append(
            f"وأنت الآن في ساعة {cur.get('planet')}: "
            f"{cur.get('طبعها', '')}"
        )
    lines.append(
        f"وحاكم اليوم كلّه {data.get('day_ruler', '')} — "
        "ومنه جاءت أسماء أيام الأسبوع في لغات كثيرة."
    )
    then = "اضغط أيّ ساعة لترى ما تصلح له وما يُتجنّب فيها."
    return _wrap("خلاصة الساعات", lines, then)


# ══════════════════════════════════════════════════════════════
# ٧ — أرباب الأزمنة
# ══════════════════════════════════════════════════════════════
def timelords(data: dict) -> dict:
    f = (data.get("firdaria") or {}).get("major") or {}
    p = data.get("profection") or {}
    lines = []
    if f.get("planet"):
        lines.append(
            f"تعيش الآن فترة يقودها {f['planet']}، "
            f"تمتدّ من {str(f.get('start', ''))[:4]} "
            f"إلى {str(f.get('end', ''))[:4]}."
        )
    if p.get("house"):
        lines.append(
            f"وسنتك هذه تُركّز على {p.get('topic') or 'باب بعينه من حياتك'} — "
            "وهذا يتبدّل كل سنة ويدور في اثنتي عشرة سنة."
        )
    lines.append(
        "وفكرة الباب كلّه أن العمر ليس مستويًا: فيه فترات يسهل فيها "
        "شيء ويصعب غيره، وأن تعرف فترتك خير من أن تلوم نفسك."
    )
    return _wrap("أين أنت من عمرك", lines,
                 "وتحت هذا: الفترات كلّها بتواريخها.")


# ══════════════════════════════════════════════════════════════
# ٨ — النشرة الشهرية
# ══════════════════════════════════════════════════════════════
def monthly(data: dict) -> dict:
    evs = data.get("events") or []
    lines = [
        f"في هذا الشهر {len(evs)} حدثًا في السماء."
        if evs else "لم أجد أحداثًا بارزة هذا الشهر."
    ]
    ecl = [e for e in evs if e.get("kind") == "eclipse"]
    if ecl:
        lines.append(
            f"وأبرزها {ecl[0].get('title', 'كسوف')} يوم {ecl[0].get('date', '')} — "
            "والعادة القديمة ألّا تُبدأ الأمور الكبيرة قريبًا منه."
        )
    retro = data.get("retrograde_windows") or []
    if retro:
        lines.append(
            f"وفيه {len(retro)} فترة يسير فيها كوكب بالاتجاه المعاكس "
            "ظاهريًّا — وقت مراجعة لا وقت ابتداء."
        )
    return _wrap("خلاصة الشهر", lines,
                 "وتحت هذا: كل حدث بيومه وساعته وما يعنيه.")


ROUTES = {
    "bulletin": bulletin, "chart": chart, "synastry": synastry,
    "search": search, "horary": horary, "hours": hours,
    "timelords": timelords, "monthly": monthly,
}


def for_route(name: str, data: dict) -> dict | None:
    """الخلاصة المناسبة لهذا المسار، إن كانت له خلاصة."""
    fn = ROUTES.get(name)
    if not fn:
        return None
    try:
        return fn(data)
    except Exception:
        # الخلاصة زينة لا أساس: إن تعذّرت فلا تُسقط الجواب كلّه
        return None
