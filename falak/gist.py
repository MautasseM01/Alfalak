_VERDICT_PLAIN = {
    "يتمّ": "الجواب الأقرب: نعم.",
    "يتمّ بعد جهد": "الجواب الأقرب: نعم، لكن بعد مفاوضة أو تنازل.",
    "يتمّ بعُسر": "الجواب الأقرب: نعم، بعد تعب وربّما خصومة.",
    "يتمّ بواسطة": "الجواب الأقرب: نعم، لكن ليس مباشرة — "
                   "يقع الأمر بوساطة شخص أو جهة.",
    "بيدك أنت": "الجواب: لا مانع خارجيّ ولا مُعين خارجيّ. القرار قرارك.",
    "لا يتمّ": "الجواب الأقرب: لا — على الحال الذي سألت عنه.",
    "تُردّ المسألة": "لا جواب في هذه اللحظة.",
}


def horary(data: dict) -> dict:
    j = data.get("judgment") or {}
    v = j.get("verdict", "")
    lines = [_VERDICT_PLAIN.get(v, v)]

    if v == "تُردّ المسألة":
        lines.append(
            "وهذا في هذا العلم جواب لا عجز: من شروطه القديمة ألّا "
            "يُجاب إلا إذا كان السؤال قد نضج فعلًا في نفس صاحبه. "
            "أعِد السؤال حين يشتدّ عليك الأمر."
        )
    elif v == "لا يتمّ":
        lines.append(
            "و«على الحال الذي سألت عنه» قيد مقصود: إن تغيّرت "
            "الأسباب تغيّر الجواب. ليست هذه نبوءة."
        )
    else:
        lines.append(
            "وهذا ميل تقرؤه السماء، لا حكم عليك. من علم أن الجواب "
            "«نعم» ثم قعد لم يقع له شيء."
        )

    lines.append(
        "ولا يُبنى على هذه الصفحة قرار طبّي ولا مالي ولا قانوني."
    )
    then = ("وتحت هذا: لماذا كان الجواب كذلك، خطوةً خطوة، "
            "بالقواعد التي مشى عليها القدماء.")
    return _wrap("الجواب باختصار", lines, then)


