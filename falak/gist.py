# -*- coding: utf-8 -*-
"""
الخلاصة — سطران قبل كل شيء، لمن لا يعرف شيئًا.

قال الفريق: «يجب الاعتماد على التبسيط والبساطة قبل كل شيء»، وقال قبلها:
«المعلومات فقيرة ولا دخول في العمق». والطلبان يبدوان متعارضين، وليسا:
التعارض يقع حين نضع العمق **والبساطة في مستوى واحد**، فيقرأ المبتدئ
جدولًا لا يفهمه ويقرأ العارف تبسيطًا يستخفّ به.

فالحلّ **ترتيب لا وسط**:

    ١. الخلاصة   سطران يفهمهما من لم يسمع بالفلك قطّ. لا مصطلح واحد.
    ٢. القراءة   ما بنيناه في falak/depth.py وأخواته.
    ٣. الجداول   الأرقام لمن يريد التحقّق.

وطبقة «اللغة المبسّطة» في falak/plain.py شيء آخر: تلك تُبدّل المصطلح
بمرادف أقرب. وهذه **لا تُبدّل، بل تُترجم المعنى إلى كلام إنسان**:
لا تقول «الكوكب الحاكم في موضع ضعف»، بل تقول «ما يقودك في الحياة
يعمل هذه المدّة بجهد أكبر من المعتاد».

**والشرط الذي يحرسها اختبار**: ألّا يظهر في الخلاصة أيّ مصطلح من
معجم plain.TERMS. فإن تسرّب مصطلح واحد سقط الاختبار — لأن الخلاصة
التي تحتاج شرحًا ليست خلاصة.
"""
from __future__ import annotations

from datetime import date as _date, datetime


# ══════════════════════════════════════════════════════════════
# أدوات
# ══════════════════════════════════════════════════════════════
def _wrap(title: str, lines: list[str], then: str = "",
          detail_label: str = "التفصيل تحتها") -> dict:
    return {
        "title": title,
        "lines": [x for x in lines if x],
        "then": then,
        "detail_label": detail_label,
    }


_WEEKDAY = ["الاثنين", "الثلاثاء", "الأربعاء", "الخميس",
            "الجمعة", "السبت", "الأحد"]


def _ar_day(iso: str) -> str:
    try:
        d = _date.fromisoformat(iso[:10])
        return _WEEKDAY[d.weekday()]
    except Exception:
        return ""


