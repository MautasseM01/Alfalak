# ٣ — التوافق
# ══════════════════════════════════════════════════════════════
def synastry(data: dict) -> dict:
    r = data.get("reading") or {}
    sc = r.get("scores") or {}
    names = r.get("names") or {}
    a, b = names.get("a", "الأوّل"), names.get("b", "الثاني")
    if not sc:
        return _wrap("خلاصة", ["تعذّر الحساب."])

    order = sorted(sc.items(), key=lambda kv: -kv[1]["score"])
    best_k, best = order[0]
    worst_k, worst = order[-1]

    WHAT = {
        "عاطفي": "الحبّ والانجذاب",
        "صداقة": "الصحبة والراحة معًا",
        "مهني": "الشراكة في عمل",
    }

    lines = [
        f"أقوى ما بين {a} و{b} هو {WHAT[best_k]}: أعلى من "
        f"{best['score']}٪ ممّن قارنّاكما بهم.",
        f"وأضعفه {WHAT[worst_k]}: أعلى من {worst['score']}٪ فقط.",
    ]
    lines.append(
        "والرقم مقارنة لا حكم: يقول أين تقفان بين آلاف الأزواج، "
        "ولا يقول ماذا تفعلان. أنجح العلاقات تُبنى بالمعاملة، "
        "وأضعفها تُهدَم بها."
    )
    then = ("وتحت هذا: ما الذي رفع كل رقم وما خفضه، وأين يقع كلٌّ "
            "منكما من حياة الآخر.")
    return _wrap("خلاصة توافقكما", lines, then)


