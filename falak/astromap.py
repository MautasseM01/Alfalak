def _norm180(x: float) -> float:
    x = (x + 180.0) % 360.0 - 180.0
    return x


def _equatorial(jd: float, code: int) -> tuple[float, float]:
    """المطالع المستقيمة والمَيْل بالدرجات."""
    x = swe.calc_ut(jd, code, chart.FLAGS | swe.FLG_EQUATORIAL)[0]
    return x[0], x[1]


def lines(when_local: datetime, lats=None) -> dict:
    """
    خطوط الأوتاد الأربعة لكل جِرم.

    يُرجع لكل جِرم: `mc` و`ic` (طولان أرضيّان)، و`asc` و`dsc`
    (قائمتا نقاط [عرض، طول] تُرسَم منحنيَين).
    """
    jd = ephem.to_jd(when_local.astimezone(ephem.UTC))
    gst = swe.sidtime(jd)                      # بالساعات
    if lats is None:
        # من −٦٠ إلى ٧٠: ما وراءهما لا يسكنه أحد تقريبًا،
        # وأكثرُ الخطوط ينقطع هناك أصلًا.
        #
        # **والخطوة درجةٌ ونصف لا نصفُ درجة.** أوّل صياغةٍ أخذت
        # ٢٦١ نقطةً لكل منحنى، فخرجت الاستجابة ١٦٥ كيلوبايت —
        # وذلك ثقلٌ يُدفَع في كل زيارة لا يراه أحد: المنحنى على
        # الشاشة لا يزيد عرضه على سبعمئة بكسل، فنقطةٌ كل درجةٍ
        # ونصف أدقُّ ممّا تُبصره العين أصلًا.
        lats = [x * 1.5 for x in range(-40, 48)]

    out = []
    for name, code, sym, _core, _cls in chart.BODIES:
        if name not in MAP_BODIES:
            continue
        try:
            ra, dec = _equatorial(jd, code)
        except Exception:
            continue
        ra_h = ra / 15.0

        mc = _norm180((ra_h - gst) * 15.0)
        ic = _norm180(mc + 180.0)

        asc, dsc = [], []
        td = math.tan(math.radians(dec))
        for phi in lats:
            c = -math.tan(math.radians(phi)) * td
            # **قطبيّ: لا شروق هنا فلا خطّ** — انظر رأس الملف
            if c < -1.0 or c > 1.0:
                continue
            h = math.degrees(math.acos(c)) / 15.0   # زاوية الساعة بالساعات
            # ومنزلتان بعد الفاصلة: الدرجة نحو ١١١ كم، فالمنزلة
            # الثانية نحو كيلومتر — وما دون ذلك زينةٌ في الملفّ.
            asc.append([round(phi, 2), round(_norm180(((ra_h - h) - gst) * 15.0), 2)])
            dsc.append([round(phi, 2), round(_norm180(((ra_h + h) - gst) * 15.0), 2)])

        out.append({"name": name, "symbol": sym, "mc": round(mc, 3),
                    "ic": round(ic, 3), "asc": asc, "dsc": dsc,
                    "dec": round(dec, 3)})

    return {"when": when_local.isoformat(timespec="minutes"),
            "bodies": out, "caveat": CAVEAT, "angles": ANGLES}


def near(when_local: datetime, lat: float, lon: float,
         orb_deg: float = 6.0) -> list[dict]:
    """
    **أيّ الخطوط تمرّ قريبًا من مكانٍ بعينه؟**

    وهذا هو المقصود عمليًّا: لا أن يرى المرء أربعين خطًّا على
    كرةٍ، بل أن يعرف ما يمرّ فوق مدينته هو.

    والحدّ بالدرجات على **طول الأرض عند عرض المكان** — فدرجةُ
    الطول عند خطّ الاستواء نحو ١١١ كم، وعند الستّين نصفُها.
    فلو قيس بالدرجة مجرّدةً لاتّسع الحدّ شمالًا وضاق جنوبًا،
    وهو خطأ. فيُضرَب في جيب تمام العرض ليصير الحدُّ مسافةً.
    """
    data = lines(when_local)
    km_per_deg = 111.32 * max(math.cos(math.radians(lat)), 0.05)
    limit_km = orb_deg * 111.32

    hits = []
    for b in data["bodies"]:
        for key, ang in (("mc", "وسط السماء"), ("ic", "وتد الأرض")):
            d = abs(_norm180(b[key] - lon)) * km_per_deg
            if d <= limit_km:
                hits.append({"body": b["name"], "symbol": b["symbol"],
                             "angle": ang, "km": round(d),
                             "text": LINE.get((b["name"], ang), "")})
        for key, ang in (("asc", "الطالع"), ("dsc", "الغارب")):
            pts = b[key]
            if not pts:
                continue
            # أقرب نقطةٍ من المنحنى عند عرض المكان
            p = min(pts, key=lambda q: abs(q[0] - lat))
            if abs(p[0] - lat) > 1.5:
                continue
            d = abs(_norm180(p[1] - lon)) * km_per_deg
            if d <= limit_km:
                hits.append({"body": b["name"], "symbol": b["symbol"],
                             "angle": ang, "km": round(d),
                             "text": LINE.get((b["name"], ang), "")})

    hits.sort(key=lambda x: x["km"])
    return hits


def coverage() -> dict:
    return {"أجرام": len(MAP_BODIES), "أوتاد": len(ANGLES),
            "نصوص": len(LINE)}
