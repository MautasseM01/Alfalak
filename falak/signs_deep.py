def read(body: str, sign: str) -> str:
    """نصّ هذا الجِرم في هذا البرج، أو فراغٌ إن لم يُكتب."""
    pair = TABLES.get(body)
    if not pair:
        return ""
    table, generational = pair
    txt = table.get(sign, "")
    if not txt:
        return ""
    return f"{txt} {GEN_NOTE}" if generational else txt


def coverage() -> dict:
    return {"أجرام مُضافة": len(TABLES),
            "نصوص": sum(len(t) for t, _ in
                        {id(t): (t, g) for t, g in TABLES.values()}.values()),
            "علامات جيل": sum(1 for _, g in TABLES.values() if g)}
