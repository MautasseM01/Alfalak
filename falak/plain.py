PROTECTED = _protected_names()

_ARABIC = r"ء-ي"
_ORDERED = sorted(TERMS, key=lambda t: -len(t[0]))

# مرور واحد: نبني نمطًا واحدًا يجمع كل المصطلحات، فلا يتعاقب الاستبدال
# ولا يُبدَّل ما وُضع بين قوسين. والحدود تمنع مطابقة جزء من كلمة أطول.
# الحدود: المصطلح لا يكون جزءًا من كلمة أطول. لكن العربية تُلصق سوابق
# العطف والجرّ (و ف ب ل ك) بأوّل الكلمة، فنسمح بها وحدها.
_PATTERN = re.compile(
    r"(?:(?<![" + _ARABIC + r"])|(?<=[وفبلك]))(" +
    "|".join(re.escape(t[0]) for t in _ORDERED) +
    r")(?![" + _ARABIC + r"])"
)
_MAP = {t[0]: (t[1], t[2]) for t in _ORDERED}


def simplify(text: str, keep_original: bool = True) -> str:
    """
    يُعيد صوغ نصّ بلغة عامّة.

    keep_original: يذكر المصطلح الأصلي بين قوسين عند أوّل ظهور،
    فيتعلّمه القارئ بدل أن يُحرَم منه.
    """
    if not text:
        return text

    # ١ — حماية أسماء الأعلام بعلامات مؤقّتة
    guards: dict[str, str] = {}
    out = text
    for i, name in enumerate(PROTECTED):
        if name in out:
            token = f"\x00{i}\x00"
            guards[token] = name
            out = out.replace(name, token)

    # ٢ — مرور واحد على المصطلحات
    seen: set[str] = set()

    def repl(m):
        term = m.group(1)
        plain_word, show_once = _MAP[term]
        # إن كان البديل يحمل قوسين أصلًا (كذكر الدرجة) فلا نُضيف قوسين
        # آخرين للمصطلح — الرقم وحده يكفي للتعليم.
        if (keep_original and show_once and term not in seen
                and "(" not in plain_word):
            seen.add(term)
            return f"{plain_word} ({term})"
        return plain_word

    out = _PATTERN.sub(repl, out)

    # ٣ — إعادة الأعلام
    for token, name in guards.items():
        out = out.replace(token, name)
    return out


def simplify_deep(obj, keys=("text", "note", "summary", "تصلح", "تُتجنّب",
                             "طبعها", "desc", "good_for", "rule",
                             "verdict_note", "day_ruler_note", "sect_note",
                             "mood_text", "dignity", "dignity_note",
                             "meaning", "title", "balance", "almuten"),
                  keep_original: bool = False):
    """يمرّ على بنية كاملة ويُبسّط الحقول النصّية المعروفة."""
    if isinstance(obj, dict):
        return {k: (simplify(v, keep_original) if k in keys and isinstance(v, str)
                    else simplify_deep(v, keys, keep_original))
                for k, v in obj.items()}
    if isinstance(obj, list):
        return [simplify_deep(x, keys, keep_original) for x in obj]
    return obj


def label(text: str, level: str = DEFAULT_LEVEL) -> str:
    """عنوان واجهة بحسب المستوى."""
    if level != "plain":
        return text
    return UI_LABELS.get(text, text)


