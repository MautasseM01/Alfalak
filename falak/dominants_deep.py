def _top(d: dict):
    if not d:
        return None, None, 0.0, 0.0
    items = sorted(d.items(), key=lambda kv: -kv[1])
    hi, lo = items[0], items[-1]
    return hi[0], lo[0], hi[1], lo[1]


def read(dom: dict) -> dict:
    """
    يُرجع {"elements","modes","planets","caveat"} — نصًّا لكل رسم،
    فيصير تحت كل شريطٍ معنًى لا نسبةٌ مجرّدة.
    """
    out = {"caveat": CAVEAT}

    el_hi, el_lo, hv, lv = _top(dom.get("elements") or {})
    if el_hi:
        strong = ELEMENT.get(el_hi, ("", ""))[0]
        weak = ELEMENT.get(el_lo, ("", ""))[1]
        out["elements"] = (
            f"**الغالب: {el_hi} ({hv:g}٪).** {strong} "
            f"**وأضعفها: {el_lo} ({lv:g}٪).** {weak} "
            "والناقص بابٌ يُتعلَّم، لا عيبٌ يُلام عليه.")

    md_hi, md_lo, hv, lv = _top(dom.get("modes") or {})
    if md_hi:
        strong = MODE.get(md_hi, ("", ""))[0]
        weak = MODE.get(md_lo, ("", ""))[1]
        out["modes"] = (
            f"**الغالب: {md_hi} ({hv:g}٪).** {strong} "
            f"**وأضعفها: {md_lo} ({lv:g}٪).** {weak}")

    pl = dom.get("planets") or {}
    if pl:
        items = sorted(pl.items(), key=lambda kv: -kv[1])
        first, second = items[0], (items[1] if len(items) > 1 else None)
        txt = PLANET.get(first[0], "")
        gap = (first[1] - second[1]) if second else first[1]
        # الفارق يُغيّر الحكم: غلبةٌ حاسمة أم كوكبان يتنازعان
        if second and gap < 3:
            shape = (f"و**{second[0]} يُزاحمه** ({second[1]:g}٪ مقابل "
                     f"{first[1]:g}٪) — فخريطتك بين سيّدين لا سيّدٍ واحد، "
                     "وأكثر تردّدك من هنا.")
        elif second:
            shape = (f"ويليه {second[0]} ({second[1]:g}٪) بفارقٍ واضح، "
                     "فالغلبة له لا تُنازَع.")
        else:
            shape = ""
        out["planets"] = (f"**أقوى الأجرام: {first[0]} ({first[1]:g}٪).** "
                          f"{txt} {shape}").strip()
    return out


