def _key(a: str, b: str, table: dict):
    if (a, b) in table:
        return (a, b)
    if (b, a) in table:
        return (b, a)
    return None


_EASY = {"تسديس", "تثليث", "خُمسي", "توازي ناقص"}


def pair_text(a: str, b: str, aspect: str) -> dict:
    """نصّ وصلة بين خريطتين. يُرجع {"theme","text","written"}."""
    a = "ليليث" if a == "ليليث الحقيقية" else a
    b = "ليليث" if b == "ليليث الحقيقية" else b

    k = _key(a, b, SYN_PAIRS)
    if k:
        d = SYN_PAIRS[k]
        if aspect == "اقتران":
            return {"theme": d["theme"], "text": d["اقتران"], "written": True}
        key = "سهل" if aspect in _EASY else "صعب"
        return {"theme": d["theme"], "text": d[key], "written": True}

    k = _key(a, b, SYN_OUTER)
    if k:
        return {"theme": f"{k[0]} على {k[1]}", "text": SYN_OUTER[k],
                "written": True}

    k = _key(a, b, ANGLE_TEXT)
    if k:
        return {"theme": f"{k[1]} على {k[0]} — وصلة وتد",
                "text": ANGLE_TEXT[k], "written": True}

    k = _key(a, b, SLOW_PAIRS)
    if k:
        return {"theme": "علامة جيل — تُخبر بفارق السنّ لا بما بينكما",
                "text": SLOW_PAIRS[k], "written": True}

    return {"theme": "", "text": "", "written": False}


def coverage() -> dict:
    return {
        "أزواج التوافق": len(SYN_PAIRS),
        "نصوص الأزواج": sum(len(v) - 1 for v in SYN_PAIRS.values()),
        "نصوص الخارجية والنقاط": len(SYN_OUTER),
        "نصوص الأوتاد": len(ANGLE_TEXT),
        "علامات الجيل": len(SLOW_PAIRS),
        "نصوص تراكب البيوت": len(OVERLAY_TEXT),
        "المجموع": (sum(len(v) for v in SYN_PAIRS.values())
                    + len(SYN_OUTER) + len(ANGLE_TEXT)
                    + len(SLOW_PAIRS) + len(OVERLAY_TEXT)),
    }
