def _jd(y: int, m: int, d: int, hour: float = 12.0) -> float:
    """
    اليوم اليولياني — **بالتقويم الذي سُجّل به التاريخ**.

    ومن أخذ تاريخًا يوليانيًّا فحسبه غريغوريًّا أخطأ بأيّام،
    وذلك يُزحزح القمر عشراتِ الدرجات. فالعلَم يُختار هنا.
    """
    cal = swe.GREG_CAL if (y, m, d) >= GREG_START else swe.JUL_CAL
    return swe.julday(y, m, d, hour, cal)


def _at(jd: float) -> dict:
    """مواضع الأجرام عند لحظةٍ بعينها."""
    out = {}
    for name, code, sym, _c, _cl in chart.BODIES:
        try:
            x = swe.calc_ut(jd, code, chart.FLAGS)[0]
        except Exception:
            continue
        L = x[0] % 360.0
        # `speed` تلزم `find_aspects` لتمييز المُقبِلة من المُدبِرة
        out[name] = {"name": name, "symbol": sym, "lon": L,
                     "speed": x[3], "retro": x[3] < 0, **chart.dms(L)}
    return out


def find(key: str) -> dict | None:
    for f in FIGURES:
        if f[0] == key:
            return dict(zip(("key", "name", "note", "y", "m", "d",
                             "place", "lat", "lon", "rating"), f))
    return None


def listing(q: str = "") -> list[dict]:
    """القائمة، مع بحثٍ بسيط في الاسم والوصف."""
    q = (q or "").strip()
    out = []
    for f in FIGURES:
        row = dict(zip(("key", "name", "note", "y", "m", "d",
                        "place", "lat", "lon", "rating"), f))
        if q and q not in row["name"] and q not in row["note"] \
           and q not in row["place"]:
            continue
        row["date"] = f"{row['y']}-{row['m']:02d}-{row['d']:02d}"
        row["rating_text"] = RATINGS.get(row["rating"], "")
        row["julian"] = (row["y"], row["m"], row["d"]) < GREG_START
        out.append(row)
    return out


def sky(key: str) -> dict | None:
    """
    ما يصحّ أن يُقال بالتاريخ وحده.

    **ولا طالع ولا بيوت هنا.** انظر رأس الملفّ: الطالع يدور
    اثنتي عشرة مرّةً في اليوم، فرسمُه بغير ساعةٍ اختراع.
    """
    f = find(key)
    if not f:
        return None

    jd0 = _jd(f["y"], f["m"], f["d"], 0.0)      # أوّل اليوم
    jd1 = jd0 + 1.0                              # آخره
    mid = _at(jd0 + 0.5)
    a, b = _at(jd0), _at(jd1)

    bodies = []
    for name, cur in mid.items():
        if name in ("الذنب", "ليليث الحقيقية"):
            continue
        s0 = a.get(name, {}).get("sign")
        s1 = b.get(name, {}).get("sign")
        # **البرج يقينٌ إن لم يتبدّل في اليوم كلّه** — وإلّا فلا
        sure = (s0 == s1 == cur["sign"])
        row = {"name": name, "symbol": cur["symbol"], "sign": cur["sign"],
               "text": cur["text"], "retro": cur["retro"], "sure": sure}
        if not sure:
            row["span"] = f"{s0} ← {s1}"
        # القمر يقطع ١٣° في اليوم، فمداه يُذكَر لا موضعه
        if name == "القمر":
            row["moved"] = round((b[name]["lon"] - a[name]["lon"]) % 360.0, 1)
        bodies.append(row)

    # ــ الزوايا: بين البطيئة وحدها ــ
    # زوايا القمر تتبدّل في ساعات، فلا تصحّ بتاريخٍ مجرّد.
    SLOW = ["الشمس", "عطارد", "الزهرة", "المريخ", "المشتري", "زحل",
            "أورانوس", "نبتون", "بلوتو"]
    lst = [dict(mid[n], **{"class": "كوكب"}) for n in SLOW if n in mid]
    aspects = [x for x in chart.find_aspects(lst, minor=False)]

    f = dict(f)
    f.update({
        "date": f"{f['y']}-{f['m']:02d}-{f['d']:02d}",
        "julian": (f["y"], f["m"], f["d"]) < GREG_START,
        "rating_text": RATINGS.get(f["rating"], ""),
        "disputed": DISPUTED.get(key, ""),
        "bodies": bodies, "aspects": aspects,
        "no_time": NO_TIME,
        "sun": next((b for b in bodies if b["name"] == "الشمس"), None),
    })
    return f


def moon_check(key: str) -> str:
    """جملةٌ صريحة عن القمر — أكثرُ ما يُخطئ فيه الناس."""
    s = sky(key)
    if not s:
        return ""
    m = next((b for b in s["bodies"] if b["name"] == "القمر"), None)
    if not m:
        return ""
    if m.get("sure"):
        return (f"وكان القمر في {m['sign']} ذلك اليوم كلَّه، "
                f"فبرجُه يصحّ — أمّا درجتُه فلا، إذ سار "
                f"{m['moved']}° بين فجره وفجر غده.")
    return (f"**والقمر بدّل برجه في ذلك اليوم** ({m['span']}) — "
            f"فلا يُقال في أيّهما وُلد بغير ساعةٍ تُعرَف.")


