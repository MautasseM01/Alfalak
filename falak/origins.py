from __future__ import annotations

from . import dignities

SIGNS = dignities.SIGNS

# صاحبُ كل برج — من `dignities` لا يُكتَب ثانيةً
def _lord(sign: str) -> str:
    return dignities.DOMICILE[sign] if hasattr(dignities, "DOMICILE") \
        else dignities.RULERS[sign]


def indian_faces() -> dict:
    """
    أرباب الوجوه على المذهب الثاني — **بقاعدةٍ لا بجدول**.

    وجهُ البرج الأوّل لصاحبه، والثاني لصاحب البرج الذي يليه
    من مثلّثته (بعده بأربعة)، والثالث للذي بعده بثمانية.
    """
    out = {}
    for i, s in enumerate(SIGNS):
        out[s] = [_lord(SIGNS[(i + step) % 12]) for step in (0, 4, 8)]
    return out


def faces_of(lon: float) -> dict:
    """الوجه الذي يقع فيه طولٌ بروجيّ، بالمذهبين معًا."""
    sign = dignities.sign_of(lon)
    idx = min(2, int((lon % 30) // 10))
    ind = indian_faces()[sign]
    return {
        "sign": sign,
        "index": idx + 1,
        "span": f"{idx * 10}°–{idx * 10 + 10}° من {sign}",
        "global_index": SIGNS.index(sign) * 3 + idx + 1,   # ١..٣٦
        "chaldean": dignities.FACES[sign][idx],
        "indian": ind[idx],
        "agree": dignities.FACES[sign][idx] == ind[idx],
    }


