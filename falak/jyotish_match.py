# مَنغَل دوشا (المريخ)
# ══════════════════════════════════════════════════════════════
MANGAL_HOUSES = (1, 2, 4, 7, 8, 12)


def mangal_dosha(chart: dict) -> dict:
    """
    وقوع المريخ في بيوت بعينها. يُعدّ في الهند من أشدّ الموانع،
    ويُقال إنه يُبطَل إن كان عند الطرفين معًا.
    """
    m = next((b for b in chart["bodies"] if b["name"] == "المريخ"), None)
    if not m:
        return {"has": False}
    has = m["house"] in MANGAL_HOUSES
    return {
        "has": has, "house": m["house"], "sign": m["sign"],
        "note": (f"المريخ في البيت {m['house']}، وهو من البيوت "
                 "التي يُعدّ فيها «مَنغَل دوشا»."
                 if has else
                 f"المريخ في البيت {m['house']}، ولا دوشا فيه."),
    }
