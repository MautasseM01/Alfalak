def _varna(b_sign: str, g_sign: str) -> dict:
    bv, gv = VARNA[b_sign], VARNA[g_sign]
    got = 1 if _VARNA_RANK[gv] >= _VARNA_RANK[bv] else 0
    return {
        "name": "الفَرْنا", "max": 1, "got": got,
        "detail": f"هي {bv} وهو {gv}.",
        "note": ("هذا الباب **أصله تقسيم الناس طبقات**، ويُنقص الدرجة "
                 "إن كانت طبقتها أعلى. نحسبه لأنه من النظام، ولا "
                 "نُقرّه — وقيمته درجة واحدة من ستّ وثلاثين، فلا "
                 "يُبنى عليه شيء."),
        "flagged": True,
    }


def _vashya(b_sign: str, g_sign: str) -> dict:
    bv, gv = VASHYA[b_sign], VASHYA[g_sign]
    if bv == gv:
        got, why = 2, "من طبيعة واحدة، فيسهل الانقياد بينهما."
    elif {bv, gv} == {"إنسان", "رباعي"}:
        got, why = 1, "طبيعتان تتفاهمان جزئيًّا."
    elif "حشري" in (bv, gv) and "رباعي" in (bv, gv):
        got, why = 0, "طبيعتان لا تنقاد إحداهما للأخرى."
    else:
        got, why = 1, "طبيعتان مختلفتان، والتفاهم ممكن بجهد."
    return {"name": "الڤَشْيا", "max": 2, "got": got,
            "detail": f"هي {bv} وهو {gv}. {why}",
            "note": "يقيس من يجذب من، ومن يلين لمن."}


def _tara(b_nak: int, g_nak: int) -> dict:
    a = ((g_nak - b_nak) % 27) or 27
    b = ((b_nak - g_nak) % 27) or 27
    ra, rb = (a % 9) or 9, (b % 9) or 9
    bad = {3, 5, 7}
    good = (ra not in bad) + (rb not in bad)
    got = {2: 3, 1: 1.5, 0: 0}[good]
    return {"name": "التارا", "max": 3, "got": got,
            "detail": (f"العدّ منها إليه {a} فباقيه {ra}، ومنه إليها "
                       f"{b} فباقيه {rb}."),
            "note": ("يقيس صحّة كلٍّ وعمره في نظر الآخر. والبواقي "
                     "٣ و٥ و٧ تُعدّ غير مُيسّرة.")}


def _yoni(b_nak: int, g_nak: int) -> dict:
    ba, bg, *_ = _nak_attr(b_nak)
    ga, gg, *_ = _nak_attr(g_nak)
    if ba == ga:
        got, why = (4, "الحيوان واحد — أعلى ما في هذا الباب.")
    elif frozenset({ba, ga}) in _ENEMY:
        got, why = (0, "حيوانان متعاديان في هذا الجدول.")
    else:
        got, why = (2, "حيوانان محايدان.")
    return {"name": "اليوني", "max": 4, "got": got,
            "detail": f"هي {ba} ({bg}) وهو {ga} ({gg}). {why}",
            "note": ("يقيس التوافق البدني والغريزي. وجدوله الكامل "
                     "سبع وعشرون في سبع وعشرين وتختلف فيه المدارس، "
                     "فاختصرناه إلى: واحد / محايد / متعادٍ — "
                     "**وهذا اختصار منّا نقوله**.")}


def _maitri(b_sign: str, g_sign: str) -> dict:
    bl, gl = jy.OWN and _lord(b_sign), _lord(g_sign)
    if bl == gl:
        got, why = 5, "ربّ برجيهما واحد."
    else:
        r1 = jy.natural_relation(bl, gl)
        r2 = jy.natural_relation(gl, bl)
        pair = {r1, r2}
        if pair == {"صديق"}:
            got, why = 5, "صديقان في المنظومة الهندية."
        elif "صديق" in pair and "محايد" in pair:
            got, why = 4, "أحدهما صديق والآخر محايد."
        elif pair == {"محايد"}:
            got, why = 3, "محايدان."
        elif "عدوّ" in pair and "صديق" in pair:
            got, why = 1, "أحدهما صديق والآخر عدوّ."
        elif "عدوّ" in pair and "محايد" in pair:
            got, why = 0.5, "أحدهما عدوّ والآخر محايد."
        else:
            got, why = 0, "متعاديان."
    return {"name": "غْرَها مَيْتري", "max": 5, "got": got,
            "detail": f"ربّ برجها {bl} وربّ برجه {gl}. {why}",
            "note": "يقيس التفاهم الذهني والودّ العامّ."}


def _lord(sign: str) -> str:
    for p, signs in jy.OWN.items():
        if sign in signs:
            return p
    return ""


def _gana(b_nak: int, g_nak: int) -> dict:
    _a, _g, bg, _n = _nak_attr(b_nak)
    _a2, _g2, gg, _n2 = _nak_attr(g_nak)
    if bg == gg:
        got, why = 6, "من طبع واحد."
    elif {bg, gg} == {"ديفا", "إنسان"}:
        got, why = 5, "طبعان متقاربان."
    elif {bg, gg} == {"إنسان", "راكشاسا"}:
        got, why = (3 if bg == "راكشاسا" else 0,
                    "طبعان متباعدان — والدرجة تختلف بحسب أيّهما الأشدّ.")
    else:
        got, why = 0, "طبعان متضادّان في هذا الجدول."
    return {"name": "الغانا", "max": 6, "got": got,
            "detail": f"طبعها {bg} وطبعه {gg}. {why}",
            "note": "يقيس المزاج: أهو ليّن أم شديد أم بينهما."}


def _bhakoot(b_sign: str, g_sign: str) -> dict:
    from .chart import SIGNS
    bi, gi = SIGNS.index(b_sign), SIGNS.index(g_sign)
    d1 = ((gi - bi) % 12) + 1
    d2 = ((bi - gi) % 12) + 1
    pair = {d1, d2}
    bad = [{6, 8}, {5, 9}, {2, 12}]
    if any(pair == set(x) for x in bad):
        got = 0
        why = f"المسافة بينهما {d1} و{d2} — وهي من المسافات المعسِّرة."
    else:
        got, why = 7, f"المسافة بينهما {d1} و{d2} — سليمة."
    return {"name": "البهاكوت", "max": 7, "got": got,
            "detail": why,
            "note": ("يقيس الرخاء والنسل. وهو ثاني أثقل الأبواب، "
                     "وتذكر كتبهم له مُبطِلات إن كان ربّ البرجين "
                     "واحدًا أو بينهما صداقة.")}


def _nadi(b_nak: int, g_nak: int) -> dict:
    *_a, bn = _nak_attr(b_nak)
    *_b, gn = _nak_attr(g_nak)
    same = bn == gn
    return {"name": "النادي", "max": 8, "got": 0 if same else 8,
            "detail": f"ناديها {bn} وناديه {gn}."
                      + (" وهما واحد — وهذا «نادي دوشا»." if same
                         else " وهما مختلفان."),
            "note": ("أثقل الأبواب: تُرفَض به زيجات في الهند ولو بلغ "
                     "المجموع ثلاثين. **ونقول ما تقوله كتبهم أنفسها**: "
                     "له مُبطِلات — إن اتّحد برج القمر، أو اتّحدت "
                     "المنزلة واختلف ربعها، أو كان ربّ البرجين واحدًا. "
                     "فليس حكمًا نهائيًّا حتى عندهم."),
            "flagged": same}


BANDS = [
    (32, "ممتاز عندهم", "أعلى ما يُوصَف في هذا النظام"),
    (26, "جيّد", "يُقبَل بلا تحفّظ في العرف الهندي"),
    (18, "مقبول", "يُقبَل عند أكثرهم"),
    (0, "دون المعتاد", "يُتوقَّف عنده في العرف الهندي"),
]


def ashta_koota(bride: dict, groom: dict) -> dict:
    """
    الأبواب الثمانية بين خريطتين هنديّتين.

    والترتيب هنا (عروس/عريس) ليس رأيًا فينا: النظام نفسه غير
    متماثل — الفَرْنا والغانا والتارا تُحسَب باتّجاه. ونحن نُبيّن
    ذلك بدل أن نُخفيه بترتيب محايد كاذب.
    """
    bm = bride["moon_nakshatra"]
    gm = groom["moon_nakshatra"]
    b_sign = next(x["sign"] for x in bride["bodies"] if x["name"] == "القمر")
    g_sign = next(x["sign"] for x in groom["bodies"] if x["name"] == "القمر")

    kootas = [
        _varna(b_sign, g_sign),
        _vashya(b_sign, g_sign),
        _tara(bm["index"], gm["index"]),
        _yoni(bm["index"], gm["index"]),
        _maitri(b_sign, g_sign),
        _gana(bm["index"], gm["index"]),
        _bhakoot(b_sign, g_sign),
        _nadi(bm["index"], gm["index"]),
    ]
    total = sum(k["got"] for k in kootas)
    band = next(b for cut, *b in [(c, n, d) for c, n, d in BANDS]
                if total >= cut)

    return {
        "total": round(total, 1), "max": 36,
        "band": band[0], "band_note": band[1],
        "kootas": kootas,
        "moon": {"bride": {"sign": b_sign, "nakshatra": bm["name"]},
                 "groom": {"sign": g_sign, "nakshatra": gm["name"]}},
        "asymmetry_note": (
            "هذا النظام **غير متماثل**: بعض أبوابه تُحسَب باتّجاه، "
            "فتبديل الطرفين قد يُغيّر المجموع. وهو من النظام لا منّا، "
            "ونُبيّنه بدل أن نُخفيه."),
        "limits": (
            "ثمانية أرقام لا تعرف شيئًا عن شخصين. وهذا النظام يُبنى "
            "عليه الزواج في الهند، وفيه بابان نقولهما صراحةً: "
            "**الفَرْنا أصله طبقيّ**، و**النادي تُرفَض به زيجات** ولو "
            "بلغ المجموع ثلاثين — وكتبهم أنفسها تذكر له مُبطِلات. "
            "فمن ردّ إنسانًا بسبب رقم خرج من جدول فقد ظلمه."),
    }


