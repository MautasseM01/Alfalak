def planet_in_sign(planet: str, sign: str) -> str:
    if planet in SPECIFIC:
        return SPECIFIC[planet][sign]
    fn = FUNCTION.get(planet, "")
    mn = MANNER.get(sign, "")
    return f"{fn} — يعمل عندك {mn}."


def planet_in_house(planet: str, house: int) -> str:
    return f"{FUNCTION.get(planet, '')} يتركّز في {HOUSE_DOMAIN[house - 1]}."


