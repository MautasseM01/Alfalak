def aspect_text(a: str, b: str, aspect: str) -> dict:
    """
    نصّ الزاوية — مكتوب إن وُجد في falak/aspects_deep.py.

    يُرجع {"theme", "text", "written"}: «الموضوع» ما يجمع الجرمين
    في كل زاوية، و«النصّ» ما تفعله هذه الزاوية بعينها.
    """
    from .aspects_deep import pair_text
    d = pair_text(a, b, aspect)
    if d["text"]:
        return d
    ka, kb = KEYWORD.get(a, a), KEYWORD.get(b, b)
    return {
        "theme": f"{ka} ({a}) و{kb} ({b})",
        "text": f"{ka} و{kb} {ASPECT_QUALITY.get(aspect, '')}.",
        "written": False,
    }


# ── القراءة المركّبة ─────────────────────────────────────────────
def read_chart(c: dict) -> dict:
    by = {b["name"]: b for b in c["bodies"]}
    asc_sign = c["dominants"]["asc_sign"]
    asc_ruler = c["dominants"]["asc_ruler"]
    ruler = by.get(asc_ruler)
    dom = c["dominants"]

    core = []
    for name in ("الشمس", "القمر"):
        b = by[name]
        core.append({
            "title": f"{name} في {b['sign']} — البيت {b['house']}",
            "text": planet_in_sign(name, b["sign"]),
            "extra": planet_in_house(name, b["house"]),
            "dignity": b.get("dignity"),
        })
    core.insert(1, {
        "title": f"الطالع في {asc_sign}",
        "text": ASC_IN_SIGN[asc_sign],
        "extra": (f"وسيّد الخريطة {asc_ruler}، وهو في {ruler['sign']} بالبيت "
                  f"{ruler['house']}: {planet_in_house(asc_ruler, ruler['house'])}"
                  if ruler else ""),
        "dignity": ruler.get("dignity") if ruler else None,
    })

    others = []
    for name in ("عطارد", "الزهرة", "المريخ", "المشتري", "زحل",
                 "أورانوس", "نبتون", "بلوتو"):
        b = by.get(name)
        if not b:
            continue
        others.append({
            "title": f"{name} في {b['sign']} — البيت {b['house']}",
            "text": planet_in_sign(name, b["sign"]),
            "extra": planet_in_house(name, b["house"]),
            "dignity": b.get("dignity"),
        })

    top_aspects = []
    for a in [x for x in c["aspects"] if x["major"]][:8]:
        d = aspect_text(a["a"], a["b"], a["name"])
        top_aspects.append({
            "title": f"{a['a']} {a['symbol']} {a['b']} — {a['name']}",
            "theme": d["theme"],
            "text": d["text"],
            "quality": ASPECT_QUALITY.get(a["name"], ""),
            "orb": a["orb"], "polarity": a["polarity"],
            "applying": a["applying"],
        })

    el = dom["elements"]
    top_el = next(iter(el))
    low_el = list(el)[-1]
    md = dom["modes"]
    top_md = next(iter(md))

    balance = (
        f"الغالب على خريطتك العنصر {top_el} ({el[top_el]}٪): "
        f"{ELEMENT_READ[top_el]}. وأضعفها {low_el} ({el[low_el]}٪) — "
        f"وهو الباب الذي تحتاج أن تتعلّمه لا الذي تُلام عليه. "
        f"وطبعها الغالب {top_md}: قوّتك في {MODE_READ[top_md]}."
    )

    alm = c["almuten"]
    almuten_text = (
        f"أَلْمُطَن الخريطة {alm['winner']} بمجموع {alm['score']}. "
        f"هو الكوكب الذي يحكم بنيتها، ويُنظر في حاله قبل غيره: "
        f"{FUNCTION.get(alm['winner'], '')}."
    )

    lots_text = []
    for L in c["lots"]:
        if L["core"]:
            lots_text.append({
                "title": f"{L['name']} — {L['text']} (البيت {L['house']})",
                "text": L["note"],
            })

    # ملفّات البيوت والبروج المستعملة في هذه الخريطة
    from .depth import HOUSES, SIGNS_DEEP
    used_h = sorted({b["house"] for b in c["bodies"] if b.get("house")})
    used_s = sorted({b["sign"] for b in c["bodies"]})

    return {
        "profiles": {
            "houses": {str(h): HOUSES[h] for h in used_h if h in HOUSES},
            "signs": {k: SIGNS_DEEP[k] for k in used_s if k in SIGNS_DEEP},
        },
        "sect": c["sect_note"],
        "core": core,
        "others": others,
        "aspects": top_aspects,
        "balance": balance,
        "almuten": almuten_text,
        "lots": lots_text,
        # نصّ الشكل يُقرأ بأعضائه وموضعه، لا من جدولٍ مفتاحه اسمه.
        # و`p["note"]` يبقى **تعريفًا** يُعرَض عند الحاجة — والفرق
        # بينهما هو أصل الشكوى: التعريف يقول ما هو الشكل، والقراءة
        # تقول ما يصنعه شكلُك أنت.
        "patterns": [{"title": p["name"] + (f" — {p['where']}" if p["where"] else ""),
                      "text": (pdeep.read(p, c["bodies"]) or p["note"]),
                      "note": p["note"],
                      "members": p["members"]}
                     for p in c["patterns"]],
        "stars": [{"title": f"{s['body']} مع {s['star']} ({s['star_la']})",
                   "text": s["meaning"], "orb": s["orb"], "royal": s["royal"]}
                  for s in c["stars"][:6]],
    }


