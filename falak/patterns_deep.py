    if name in ("التربيع المزدوج", "الإصبع", "قبضة اليد"):
        apex = members[-1] if members else None
        h = _house_of(apex, bodies) if apex else None
        out = APEX_HOUSE.get(h, "")
        kind = {
            "التربيع المزدوج": "جرمان متقابلان يُربّعهما ثالث، والثالث هو "
                               "موضع الضغط ومفتاح الحلّ معًا",
            "الإصبع": "جرمان متوافقان يشيران معًا إلى ثالث، فيدفعانه دفعًا "
                      "خفيًّا لا يُقاوَم",
            "قبضة اليد": "جرمان متوافقان يجمعهما ثالث بزاويتين حادّتين، "
                         "فيصير له اتّجاه واحد لا يحيد",
        }[name]
        rapex = ROLE.get(apex, "")
        apex_line = (f"ورأسه {apex}" + (f" — {rapex}" if rapex else "")
                     + (f"، في البيت {HOUSE_ORD[h - 1]}" if h else "")) if apex else ""
        # البيت يقول **أين المخرج**، والجِرم يقول **ما الذي يُضغَط**.
        # وبغير الثاني يتشابه تربيعان رأساهما في بيت واحد وإن اختلف
        # جِرماهما — وقد أسقط الاختبارُ حالةً كهذه (٨٧٪).
        what = APEX_BODY.get(apex, "") if apex else ""
        return f"{kind}. {head}، {apex_line}. {what} {out}".strip()

    # ── الصليب المتقابل: الطبيعة هي المفتاح ──
    if name == "الصليب المتقابل":
        modes = {b.get("mode") for b in bodies if b.get("name") in members and b.get("mode")}
        key = modes.pop() if len(modes) == 1 else "مختلط"
        return (f"أربعة من أجرامك في تربيعات متتالية وتقابلين متقاطعين: {who}. "
                f"{MODE_CROSS.get(key, '')} وما فيه من طاقة عملٍ هائلة لا يبلغه "
                f"إلّا من احتمل ضغطه.").strip()

    # ── المستطيل الصوفي ──
    if name == "المستطيل الصوفي":
        return (f"تقابلان متوازيان تربطهما تسديسات وتثليثات: {who}. "
                f"بنيةٌ مغلقة متوازنة، فيها {roles} — ومعناها أنك تُوفّق بين "
                f"ما يظنّه الناس متناقضًا، لا لأنك تُهادن بل لأنك ترى الوجه "
                f"الذي يجمعهما. وثِقلُها أن التوازن قد يمنع الحسم.").strip()

    return ""


