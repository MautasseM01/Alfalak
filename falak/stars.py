# النجوم الأربعة الملكيّة عند الفرس والعرب
ROYAL = {"الدبران", "قلب الأسد", "قلب العقرب", "فم الحوت"}


def positions(year: float) -> list:
    """مواضع النجوم في سنة معيّنة بعد إضافة تقدّم الاعتدالين."""
    shift = (year - 2000.0) * PRECESSION_PER_YEAR
    out = []
    for ar, la, lon2000, mag, meaning in STARS:
        out.append({
            "ar": ar, "la": la, "lon": (lon2000 + shift) % 360.0,
            "mag": mag, "meaning": meaning, "royal": ar in ROYAL,
        })
    return out


def conjunctions(bodies: list, year: float, orb: float = 1.0,
                 angles: dict | None = None) -> list:
    """
    مقارنات الأجرام والأوتاد بالنجوم الثابتة.
    الوجاج ضيّق عمدًا — النجم لا يعمل إلا بالمقارنة الدقيقة.
    """
    stars = positions(year)
    targets = [(b["name"], b["lon"], "جرم") for b in bodies]
    if angles:
        for k, v in angles.items():
            targets.append((k, v if isinstance(v, float) else v["lon"], "وتد"))

    out = []
    for name, lon, kind in targets:
        for s in stars:
            d = abs(((lon - s["lon"] + 180.0) % 360.0) - 180.0)
            if d <= orb:
                out.append({
                    "body": name, "kind": kind, "star": s["ar"], "star_la": s["la"],
                    "orb": round(d, 2), "mag": s["mag"], "royal": s["royal"],
                    "meaning": s["meaning"],
                    "strength": round(max(0.0, 1 - d / orb), 2),
                })
    out.sort(key=lambda x: x["orb"])
    return out
