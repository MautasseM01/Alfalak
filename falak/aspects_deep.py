# الزوايا المُيسِّرة والمُعسِّرة، لاختيار وجه النصّ في الجدول الخارجي
_EASY = {"تسديس", "تثليث", "خُمسي"}
_HARD = {"تربيع", "تقابل", "نصف تربيع", "تربيع ونصف", "سُدسي ناقص"}
# الاقتران بينهما: يُقرأ بوجهيه معًا


def _key(a: str, b: str, table: dict) -> tuple | None:
    """المفتاح لا يعتمد على ترتيب الجرمين."""
    if (a, b) in table:
        return (a, b)
    if (b, a) in table:
        return (b, a)
    return None


def pair_text(a: str, b: str, aspect: str) -> dict:
    """
    يُرجع {"theme", "text", "written"}.

    written=True إن كان النصّ مكتوبًا لهذا التركيب بعينه،
    False إن اضطررنا إلى الصياغة العامّة — حتى نعرف أين نُكمل.
    """
    # ليليث الحقيقية تُقرأ قراءة ليليث الوسطى
    a = "ليليث" if a == "ليليث الحقيقية" else a
    b = "ليليث" if b == "ليليث الحقيقية" else b

    k = _key(a, b, PAIRS)
    if k:
        d = PAIRS[k]
        if aspect in d:
            return {"theme": d["theme"], "text": d[aspect], "written": True}
        # زاوية صغرى بين كوكبين تراثيين: موضوع الزوج + طبع الزاوية
        nat = MINOR_NATURE.get(aspect)
        if nat:
            return {"theme": d["theme"], "text": nat, "written": True}
        return {"theme": d["theme"], "text": d["theme"], "written": False}

    k = _key(a, b, GENERATIONAL)
    if k:
        return {"theme": "علامة جيل — تُقرأ ببيتها لا ببرجها",
                "text": GENERATIONAL[k], "written": True}

    k = _key(a, b, OUTER_PAIRS)
    if k:
        d = OUTER_PAIRS[k]
        if aspect == "اقتران":
            txt = f"{d['سهل']} وفي المقابل: {d['صعب']}"
        elif aspect in _HARD:
            txt = d["صعب"]
        elif aspect in MINOR_NATURE:
            txt = f"{MINOR_NATURE[aspect]} {d['سهل'] if aspect in _EASY else d['صعب']}"
        else:
            txt = d["سهل"]
        return {"theme": d["theme"], "text": txt, "written": True}

    return {"theme": "", "text": "", "written": False}


def coverage() -> dict:
    """كم تركيبًا مكتوبًا فعلًا — رقم يُذكر ولا يُدَّعى."""
    n_pairs = sum(len(v) - 1 for v in PAIRS.values())      # ناقص «الموضوع»
    n_outer = len(OUTER_PAIRS) * 2                          # سهل + صعب
    return {
        "أزواج تراثية": len(PAIRS),
        "نصوص الزوايا التراثية": n_pairs,
        "أزواج خارجية": len(OUTER_PAIRS),
        "نصوص خارجية": n_outer,
        "علامات جيل": len(GENERATIONAL),
        "زوايا صغرى": len(MINOR_NATURE),
        "المجموع": (n_pairs + n_outer + len(PAIRS) + len(OUTER_PAIRS)
                    + len(GENERATIONAL) + len(MINOR_NATURE)),
    }
