def house_text(planet: str, house: int) -> str:
    """نصّ الكوكب في البيت — مكتوب إن وُجد، وإلا فبصيغة الباب."""
    tbl = PLANET_IN_HOUSE.get(planet)
    if tbl and house in tbl:
        return tbl[house]
    base = PLANET_IN_HOUSE_FALLBACK.get(planet)
    h = HOUSES.get(house)
    if base and h:
        return f"{h['name']} — {h['rules'].split('،')[0]}. {base}"
    return ""


