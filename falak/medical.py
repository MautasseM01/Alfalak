def temperament(c: dict) -> dict:
    """
    المِزاج الغالب — **بقاعدةٍ موزونة لا بانطباع**.

    `c` من `chart.compute`. ويُرجع الأخلاط بأوزانها ومصادرها،
    فيُرى **من أين جاء الحكم** لا الحكمُ وحده.
    """
    score = {h: 0 for h in HUMORS}
    why = []

    def add(humor, w, src):
        if not humor:
            return
        score[humor] += w
        why.append({"humor": humor, "weight": w, "from": src})

    asc_sign = c["angles"]["الطالع"]["sign"]
    add(ELEMENT_HUMOR[dignities.ELEMENT[asc_sign]],
        WEIGHTS["برج الطالع"], f"الطالع في {asc_sign}")

    lord = dignities.DOMICILE[asc_sign]
    add(PLANET_HUMOR.get(lord), WEIGHTS["صاحب الطالع"],
        f"صاحب الطالع {lord}")

    moon = next((b for b in c["bodies"] if b["name"] == "القمر"), None)
    if moon:
        add(ELEMENT_HUMOR[dignities.ELEMENT[moon["sign"]]],
            WEIGHTS["القمر"], f"القمر في {moon['sign']}")

    sun = next((b for b in c["bodies"] if b["name"] == "الشمس"), None)
    if sun:
        add(ELEMENT_HUMOR[dignities.ELEMENT[sun["sign"]]],
            WEIGHTS["برج الشمس (الفصل)"], f"الشمس في {sun['sign']}")

    for b in c["bodies"]:
        if b.get("house") == 1 and b["name"] in PLANET_HUMOR:
            add(PLANET_HUMOR[b["name"]], WEIGHTS["كوكب في البيت الأوّل"],
                f"{b['name']} في البيت الأوّل")

    total = sum(score.values()) or 1
    ranked = sorted(score.items(), key=lambda x: -x[1])
    top, second = ranked[0], ranked[1]

    # **ولا يُقال «غالب» لما لم يغلب**: فارقُ درجةٍ ليس غلبة.
    mixed = (top[1] - second[1]) <= 1
    return {
        "scores": {h: {"points": v, "pct": round(v * 100 / total)}
                   for h, v in score.items()},
        "top": top[0], "second": second[0], "mixed": mixed,
        "reading": (f"مِزاجٌ مركَّب بين **{top[0]}** و**{second[0]}** — "
                    f"ولا يغلب أحدُهما."
                    if mixed else
                    f"الغالب **{top[0]}** ({HUMORS[top[0]]['quality']})، "
                    f"ويليه {second[0]}."),
        "why": why,
        "method": METHOD,
    }


def body_map(c: dict) -> list[dict]:
    """
    مواضعُ البدن التي فيها أجرام — **على قدر ما فيها لا كلَّها**.

    ولا يُقال «هنا علّة»: يُقال **هنا تزاحُم**، والقدماء عدّوا
    الموضعَ المزدحم موضعَ شدّةٍ ونشاطٍ معًا لا موضعَ مرضٍ وحده.
    """
    by_sign = {}
    for b in c["bodies"]:
        if b["name"] in ("الذنب", "ليليث الحقيقية"):
            continue
        by_sign.setdefault(b["sign"], []).append(b["name"])

    out = []
    for s in SIGNS:
        part, note = MELOTHESIA[s]
        out.append({
            "sign": s, "part": part, "note": note,
            "bodies": by_sign.get(s, []),
            "count": len(by_sign.get(s, [])),
        })
    return out


def sixth(c: dict) -> dict:
    """
    البيت السادس — بيتُ العلّة عندهم، **وبيتُ العمل اليومي معًا**.

    ويُذكَر الوجهان: فمن أفرد الأوّل أفزع، ومن أفرد الثاني كتم.
    """
    cusp = next((h for h in c["houses"]["cusps"] if h["house"] == 6), None)
    if not cusp:
        return {}
    sign = dignities.sign_of(cusp["lon"])
    lord = dignities.DOMICILE[sign]
    where = next((b for b in c["bodies"] if b["name"] == lord), None)
    inside = [b["name"] for b in c["bodies"] if b.get("house") == 6]
    return {
        "sign": sign, "lord": lord,
        "lord_house": (where or {}).get("house"),
        "bodies": inside,
        "note": ("البيت السادس عندهم بيتُ العلّة والخدمة معًا — "
                 "**والعملُ اليوميّ والبدن بابٌ واحد**: ما يُتعِب "
                 "أحدَهما يُتعِب الآخر."),
    }


