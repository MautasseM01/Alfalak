# -*- coding: utf-8 -*-
"""
الزوايا الخفيّة — ما لا تُظهره العجلة أصلًا.

──────────────────────────────────────────────────────────────────
**لماذا «خفيّة»؟**

العجلة تعرض **الطول البروجي وحده**: أين وقع الجِرم على دائرة
البروج. وهذا يكفي للزوايا المعروفة — الاقتران والتربيع والتثليث.

لكنّ للجِرم موضعًا آخر لا تُظهره العجلة قطّ: **بُعده عن معدّل
النهار** شمالًا أو جنوبًا، وهو المَيْل. وكوكبان قد يكون بينهما
تسعون درجةً في البروج — فيبدوان متخاصمين — **وهما على مَيْلٍ
واحد**، فيعملان كالمقترنَين تمامًا.

فهذه زوايا **تُحسَب ولا تُرسَم**. وهي في «الخريطة الموسّعة» عند
Astrodienst، ولا وجود لها بالعربية.

──────────────────────────────────────────────────────────────────
**بابان لا باب واحد**

**١. الموازاة بالمَيْل** (parallel / contra-parallel)

المَيْل بُعد الجِرم عن معدّل النهار، من ٠ إلى نحو ٢٣° للشمس
وأكثر لبعض الكواكب. فإن تساوى مَيْلا جِرمين **في الجهة نفسها**
فذلك «توازٍ»، ويعمل عمل الاقتران. وإن تساويا **في جهتين
مختلفتين** فذلك «توازٍ مضادّ»، ويعمل عمل المقابلة.

والحدّ ضيّق: **درجةٌ واحدة**. لأن المَيْل يتبدّل بطيئًا، فحدٌّ
واسعٌ يجعل نصف الخريطة متوازيًا.

**٢. الأنطسيا** — وهي عربيّة بطلَميّة، لا غربيّة حديثة

قدماء الصناعة سمّوها **الموازاة في البروج**: درجتان يتساوى
نهارُهما، لتقابلهما حول محور الانقلابين. فأوّل السرطان يقابل
آخر الجوزاء، وأوّل الجدي يقابل آخر القوس. والحساب:

    الأنطسيون = ١٨٠° − الطول            (محورُه السرطان/الجدي)
    المضادّ    = ٣٦٠° − الطول            (محورُه الحمل/الميزان)

وكان القدماء يعدّونها **صداقةً خفيّة** بين الدرجتين: ما ينزل
بإحداهما يمسّ الأخرى وإن لم تكن بينهما زاويةٌ ظاهرة.

──────────────────────────────────────────────────────────────────
**وحكمٌ في القراءة**

هذه **تُضاف ولا تُبدِّل**. من رأى تربيعًا في العجلة ثم وجد
توازيًا بين الجِرمين نفسيهما، فذلك يشتدّ لا ينقلب. **ولا
يُبنى حكمٌ على خفيٍّ وحده** — فالظاهر أوثق، والخفيّ يُعلّل
ما لم يُفسَّر بالظاهر.
"""
from __future__ import annotations

import swisseph as swe

from . import chart

# **درجةٌ واحدة** — والمَيْل بطيء التبدّل. انظر رأس الملفّ.
PARALLEL_ORB = 1.0
# والأنطسيا أضيق: هي تطابق درجةٍ بدرجة عند القدماء
ANTISCIA_ORB = 1.5

SKIP = ("الذنب", "ليليث الحقيقية")

KINDS = {
    "توازٍ": ("يعمل عمل الاقتران: يمتزجان ويشتدّ أثرهما معًا",
              "≡"),
    "توازٍ مضادّ": ("يعمل عمل المقابلة: يتجاذبان من طرفين",
                    "≢"),
    "أنطسيون": ("صداقةٌ خفيّة: ما نزل بأحدهما مسّ الآخر",
                "⊙|"),
    "أنطسيون مضادّ": ("خفاءٌ فيه معارضة: يتنازعان من حيث لا يُرى",
                      "|⊙"),
}

METHOD = ("العجلة تعرض **الطول البروجي وحده**. وهذه زوايا من "
          "موضعٍ آخر: **المَيْل** — بُعد الجِرم عن معدّل النهار. "
          "فكوكبان بينهما تسعون درجةً في البروج قد يكونان على "
          "مَيْلٍ واحد، فيعملان كالمقترنَين. **تُحسَب ولا تُرسَم.**")

CAVEAT = ("هذه **تُضاف ولا تُبدِّل**. فمن وجد تربيعًا في العجلة "
          "ثم توازيًا بين الجِرمين نفسيهما، فذلك يشتدّ لا ينقلب. "
          "**ولا يُبنى حكمٌ على خفيٍّ وحده** — الظاهر أوثق، "
          "والخفيّ يُعلّل ما لم يُفسّره الظاهر.")

ANTISCIA_NOTE = ("الأنطسيا **عربيّة بطلَميّة لا غربيّة حديثة**: "
                 "سمّاها القدماء «الموازاة في البروج»، وهي درجتان "
                 "يتساوى نهارُهما لتقابلهما حول محور الانقلابين — "
                 "فأوّل السرطان يوازي آخر الجوزاء.")


def _sep(a: float, b: float) -> float:
    d = abs((a - b) % 360.0)
    return min(d, 360.0 - d)


def declinations(jd: float) -> dict:
    """مَيْل كل جِرم — وهو ما لا تُظهره العجلة."""
    out = {}
    for name, code, sym, _core, _cls in chart.BODIES:
        if name in SKIP:
            continue
        try:
            x = swe.calc_ut(jd, code, chart.FLAGS | swe.FLG_EQUATORIAL)[0]
        except Exception:
            continue
        dec = x[1]
        out[name] = {
            "name": name, "symbol": sym, "dec": round(dec, 3),
            "side": "شمالي" if dec >= 0 else "جنوبي",
            # **خارج البروج**: مَيْلٌ يجاوز مَيْل الشمس الأقصى
            # (٢٣°٢٦′) يُسمّى «خارجَ الحدّ»، وعدّه القدماء شدّةً
            # في الجِرم — فيُذكَر لأنه لا يُرى في العجلة أيضًا.
            "extreme": abs(dec) > 23.44,
            "text": f"{abs(dec):.1f}° {'شمالًا' if dec >= 0 else 'جنوبًا'}",
        }
    return out


def antiscion(lon: float) -> tuple[float, float]:
    """(الأنطسيون، المضادّ) لطولٍ بروجيّ."""
    return (180.0 - lon) % 360.0, (360.0 - lon) % 360.0


def find(jd: float, bodies: list) -> dict:
    """
    الزوايا الخفيّة كلّها بين أجرام الخريطة.

    `bodies` من `chart.compute` — فيها `name` و`lon`.
    """
    dec = declinations(jd)
    lon = {b["name"]: b["lon"] for b in bodies if b["name"] not in SKIP}
    names = [n for n in lon if n in dec]

    par, ant = [], []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            da, db = dec[a]["dec"], dec[b]["dec"]

            # ــ الموازاة بالمَيْل ــ
            same = (da >= 0) == (db >= 0)
            d = abs(abs(da) - abs(db))
            if d <= PARALLEL_ORB:
                kind = "توازٍ" if same else "توازٍ مضادّ"
                par.append({
                    "a": a, "b": b, "kind": kind, "symbol": KINDS[kind][1],
                    "orb": round(d, 2), "note": KINDS[kind][0],
                    "a_dec": dec[a]["text"], "b_dec": dec[b]["text"],
                })

            # ــ الأنطسيا ــ
            # **لا تُحسَب من الأجرام إلى الأجرام مباشرةً**، بل
            # يُنعكس أحدُهما ثم يُقاس بُعده عن الآخر.
            for lbl, ref in (("أنطسيون", antiscion(lon[a])[0]),
                             ("أنطسيون مضادّ", antiscion(lon[a])[1])):
                s = _sep(ref, lon[b])
                if s <= ANTISCIA_ORB:
                    ant.append({
                        "a": a, "b": b, "kind": lbl, "symbol": KINDS[lbl][1],
                        "orb": round(s, 2), "note": KINDS[lbl][0],
                    })

    par.sort(key=lambda x: x["orb"])
    ant.sort(key=lambda x: x["orb"])

    # ــ ما يُضيفه الخفيّ على الظاهر ــ
    # الفائدة كلّها هنا: أن يُعرَف **أيّ زوجٍ لا زاوية ظاهرة
    # بينه** — فذلك وحده خبرٌ جديد. وما كان بينهما زاويةٌ
    # ظاهرة فالخفيّ فيه تأكيدٌ لا كشف.
    seen = {frozenset((x["a"], x["b"])) for x in bodies_pairs(bodies)}
    for x in par + ant:
        x["new"] = frozenset((x["a"], x["b"])) not in seen

    return {
        "declinations": [dec[n] for n in names],
        "parallels": par, "antiscia": ant,
        "extreme": [dec[n] for n in names if dec[n]["extreme"]],
        "method": METHOD, "caveat": CAVEAT, "antiscia_note": ANTISCIA_NOTE,
        "orbs": {"الموازاة": PARALLEL_ORB, "الأنطسيا": ANTISCIA_ORB},
    }


def bodies_pairs(bodies: list) -> list[dict]:
    """أزواج الأجرام التي بينها زاويةٌ ظاهرة في العجلة."""
    lst = [b for b in bodies if b["name"] not in SKIP]
    try:
        return chart.find_aspects(lst, minor=False)
    except Exception:
        return []


def coverage() -> dict:
    return {"أبواب": len(KINDS), "حدود": 2}
