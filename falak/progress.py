def _sep(a: float, b: float) -> float:
    d = abs((a - b) % 360.0)
    return min(d, 360.0 - d)


def prog_moment(birth: datetime, target: datetime) -> tuple[datetime, float]:
    """لحظة التسيير: المولد + (سنو العمر) أيّامًا. ويُرجع العمر معها."""
    years = (target - birth).total_seconds() / (TROPICAL * 86400.0)
    return birth + timedelta(days=years), years


def compute(birth: datetime, lat: float, lon: float, tzname: str,
            target: datetime, system: str = "whole") -> dict:
    """
    الخريطة المُسيَّرة والقوس الشمسي معًا، ومسائلهما إلى المولد.
    """
    natal = chart.compute(birth, lat, lon, system, tzname,
                          minor_aspects=False)
    when, age = prog_moment(birth, target)
    # **المكان مكانُ المولد**: التسيير يُحرّك الزمن لا الأرض.
    prog = chart.compute(when, lat, lon, system, tzname,
                         minor_aspects=False)

    nat_lon = {b["name"]: b["lon"] for b in natal["bodies"]}
    for k, v in natal["angles"].items():
        nat_lon[k] = v["lon"]
    prg_lon = {b["name"]: b["lon"] for b in prog["bodies"]}

    arc = (prg_lon["الشمس"] - nat_lon["الشمس"]) % 360.0

    # `house_of` تأخذ قائمة درجات مجرّدة، و`natal["houses"]["cusps"]`
    # قائمةُ قواميس موصوفة. فتُستخرَج الدرجات مرّةً هنا.
    cusps = [h["lon"] for h in natal["houses"]["cusps"]]

    # ــ القمر المُسيَّر: الأصل في الباب ــ
    pm = next(b for b in prog["bodies"] if b["name"] == "القمر")
    # بيتُه من **بيوت المولد** لا من بيوت الخريطة المُسيَّرة —
    # فالمقصد أين يقع الفصل من حياة صاحبه، لا من سماء ذلك اليوم.
    pm_house = chart.house_of(pm["lon"], cusps)
    moon = {
        "text": pm["text"], "sign": pm["sign"], "house": pm_house,
        "sign_read": PMOON_SIGN.get(pm["sign"], ""),
        "house_read": PMOON_HOUSE.get(pm_house, ""),
        "next": _next_sign(birth, lat, lon, tzname, target, system, pm["sign"]),
    }

    ps = next(b for b in prog["bodies"] if b["name"] == "الشمس")
    ns = next(b for b in natal["bodies"] if b["name"] == "الشمس")
    sun = {"text": ps["text"], "sign": ps["sign"], "natal_sign": ns["sign"],
           "shifted": ps["sign"] != ns["sign"],
           "note": SUN_SHIFT if ps["sign"] != ns["sign"] else ""}

    # ــ زوايا المُسيَّر إلى المولد ــ
    hits = []
    for name in DIRECT_FROM:
        if name not in prg_lon:
            continue
        for tgt in TO_NATAL:
            if tgt not in nat_lon:
                continue
            sep = _sep(prg_lon[name], nat_lon[tgt])
            for ang, (an, sym) in ARC_ANGLES.items():
                d = abs(sep - ang)
                if d <= ARC_ORB:
                    hits.append({"kind": "تسيير", "body": name,
                                 "target": tgt, "angle": ang, "name": an,
                                 "symbol": sym, "orb": round(d, 2)})

    # ــ القوس الشمسي: كل نقطةٍ تُزاد قوسًا واحدًا ــ
    # سرعتُه تُقاس من صاحبها لا تُفترَض: من وُلد والشمسُ بطيئة
    # (في الأوج صيفًا) قوسُه أبطأ من درجةٍ في السنة، والعكس.
    rate = (arc / age) if age > 1 else 1.0
    arcs = []
    for name in DIRECT_FROM + ["الطالع", "وسط السماء"]:
        if name not in nat_lon:
            continue
        moved = (nat_lon[name] + arc) % 360.0
        for tgt in TO_NATAL:
            if tgt not in nat_lon or tgt == name:
                continue
            sep = _sep(moved, nat_lon[tgt])
            for ang, (an, sym) in ARC_ANGLES.items():
                d = abs(sep - ang)
                if d <= ARC_ORB:
                    # **متى تتمّ؟ الفرق المجرَّد لا يكفي.**
                    # `_sep` يُرجع بُعدًا بلا جهة، فلا يُعرَف منه
                    # أوقعت الزاوية أم لم تقع بعد — وكان أوّل
                    # حسابٍ لي يخلط الماضي بالمستقبل. والقوس
                    # **يتقدّم ولا يرجع**، فالجهة معلومة إن حُسبت
                    # موجَّهةً: كم درجةً بقيت حتى يبلغ المقصد.
                    yrs = _to_go(moved, nat_lon[tgt], ang) / rate
                    arcs.append({"kind": "قوس", "body": name, "target": tgt,
                                 "angle": ang, "name": an, "symbol": sym,
                                 "orb": round(d, 2),
                                 "past": yrs < 0,
                                 "when": _year_text(target, yrs)})

    hits.sort(key=lambda x: x["orb"])
    arcs.sort(key=lambda x: x["orb"])

    return {
        "birth": birth.isoformat(), "target": target.isoformat(),
        "prog_moment": when.isoformat(), "age": round(age, 2),
        "arc": round(arc, 3),
        "arc_text": f"{int(arc)}° {int((arc % 1) * 60):02d}′",
        "moon": moon, "sun": sun,
        "bodies": [{"name": b["name"], "symbol": b["symbol"],
                    "text": b["text"], "sign": b["sign"],
                    "house": chart.house_of(b["lon"], cusps),
                    "retro": b["retro"]}
                   for b in prog["bodies"] if b["name"] in DIRECT_FROM],
        "hits": hits[:14], "arcs": arcs[:14],
        "method": METHOD, "arc_note": ARC_NOTE,
    }


def _to_go(moved: float, target: float, ang: int) -> float:
    """
    كم درجةً بقيت على النقطة المُسيَّرة حتى تبلغ الزاوية؟
    موجَّهةً: الموجب مستقبل، والسالب ماضٍ. ويُختار الأقرب من
    الجهتين (المقصد ± الزاوية).
    """
    best = None
    for t in ((target + ang) % 360.0, (target - ang) % 360.0):
        d = (t - moved) % 360.0
        if d > 180.0:
            d -= 360.0
        if best is None or abs(d) < abs(best):
            best = d
    return best or 0.0


def _year_text(target: datetime, yrs: float) -> str:
    """تاريخٌ تقريبيّ بالشهر — والدقّة أبعد من ذلك ادّعاء."""
    when = target + timedelta(days=yrs * TROPICAL)
    return when.strftime("%Y-%m")


def _next_sign(birth, lat, lon, tzname, target, system, now_sign) -> dict:
    """
    متى ينتقل القمر المُسيَّر إلى البرج التالي؟

    يُمسَح بالشهر لا بالثانية: القمر المُسيَّر يقطع الدرجة في شهر،
    فالشهرُ دقّةٌ كافية — **ودقّةٌ زائدة هنا كذبٌ على القارئ**،
    إذ لا يقع الحدث في يومٍ بعينه.
    """
    step = timedelta(days=30)
    t = target
    for _ in range(40):          # نحو ثلاث سنين ونصف
        t = t + step
        w, _a = prog_moment(birth, t)
        c = chart.compute(w, lat, lon, system, tzname, minor_aspects=False)
        m = next(b for b in c["bodies"] if b["name"] == "القمر")
        if m["sign"] != now_sign:
            return {"sign": m["sign"], "when": t.strftime("%Y-%m"),
                    "read": PMOON_SIGN.get(m["sign"], "")}
    return {}


def coverage() -> dict:
    return {"نصوص القمر المُسيَّر": len(PMOON_SIGN) + len(PMOON_HOUSE),
            "حالات": len(PMOON_SIGN) * len(PMOON_HOUSE)}
